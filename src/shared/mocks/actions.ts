const ck = (
  key: ActionChecklistItem['key'],
  state: ActionChecklistItem['state'],
  hint?: string,
): ActionChecklistItem => {
  const labels: Record<ActionChecklistItem['key'], string> = {
    validation: 'Input validation',
    auth: 'Auth check',
    role: 'Role check',
    mutation: 'Mutation',
    revalidate: 'revalidateTag pair',
    audit: 'Audit log',
    idempotency: 'Idempotency',
    errorEnvelope: 'Error envelope',
    transaction: 'Transaction',
  };
  return { key, state, label: labels[key], ...(hint ? { hint } : {}) };
};

