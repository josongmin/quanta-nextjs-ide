export function patchStats(patch: Patch): { added: number; removed: number; files: number } {
  const added = patch.files.reduce((s, f) => s + f.added, 0);
  const removed = patch.files.reduce((s, f) => s + f.removed, 0);
  return { added, removed, files: patch.files.length };
}

