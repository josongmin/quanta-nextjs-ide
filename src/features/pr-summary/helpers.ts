import type { Diagnostic, SemanticDiff, SemanticDiffEntry } from '@shared/types';

export type PrProfile = 'concise' | 'standard' | 'verbose';

export interface PrSections {
  behavior: boolean;
  risks: boolean;
  cost: boolean;
  tests: boolean;
  migration: boolean;
}

export const DEFAULT_SECTIONS: PrSections = {
  behavior: true,
  risks: true,
  cost: true,
  tests: true,
  migration: true,
};

export function generatePrSummary(
  profile: PrProfile,
  sections: PrSections,
  diff: SemanticDiff,
  diagnostics: Diagnostic[],
): string {
  const lines: string[] = [];
  const verbose = profile === 'verbose';
  const concise = profile === 'concise';

  lines.push(`# Semantic review — ${diff.head} vs ${diff.base}`);
  lines.push('');
  if (!concise) {
    lines.push(
      `Generated by Next Static Studio. ${diff.entries.length} behavior change${diff.entries.length === 1 ? '' : 's'} detected.`,
    );
    lines.push('');
  }

  if (sections.behavior) {
    const behaviorEntries = diff.entries.filter(
      (e): e is SemanticDiffEntry & { category: 'rendering' | 'cache' | 'boundary' | 'auth' | 'contract' } =>
        e.category !== 'cost' && e.category !== 'metadata',
    );
    if (behaviorEntries.length > 0) {
      lines.push('## Behavior changes');
      lines.push('');
      for (const e of behaviorEntries) {
        const cause = e.cause ? ` — _${e.cause}_` : '';
        lines.push(`- \`${e.scope}\`: ${e.before} → ${e.after}${cause}`);
      }
      lines.push('');
    }
  }

  if (sections.risks) {
    const errs = diagnostics.filter((d) => d.severity === 'err');
    const warns = diagnostics.filter((d) => d.severity === 'warn');
    lines.push(`## Risks (${errs.length} high · ${warns.length} medium)`);
    lines.push('');
    const top = [...errs, ...warns].slice(0, verbose ? 14 : concise ? 4 : 8);
    for (const d of top) {
      const sev = d.severity === 'err' ? '❌' : '⚠';
      lines.push(`- ${sev} **${d.title}** — \`${d.scope}\``);
      if (verbose && d.evidence.length > 0) {
        for (const e of d.evidence.slice(0, 2)) {
          lines.push(`    - ${e.label}`);
        }
      }
    }
    lines.push('');
  }

  if (sections.cost) {
    const costEntries = diff.entries.filter((e) => e.category === 'cost');
    const renderingEntries = diff.entries.filter((e) => e.category === 'rendering');
    if (costEntries.length > 0 || renderingEntries.length > 0) {
      lines.push('## Cost');
      lines.push('');
      if (renderingEntries.length > 0) {
        const dynamics = renderingEntries.filter((e) =>
          e.after.toLowerCase().includes('dynamic'),
        ).length;
        lines.push(
          `${dynamics > 0 ? `+${dynamics}` : '0'} routes ISR/static → Dynamic. Estimated server cost +${Math.round(dynamics * 6)}%.`,
        );
      }
      for (const e of costEntries) {
        lines.push(`- \`${e.scope}\`: ${e.before} → ${e.after}`);
      }
      lines.push('');
    }
  }

  if (sections.tests) {
    lines.push('## Tests');
    lines.push('');
    lines.push('0 new tests. Coverage unchanged.');
    if (verbose) {
      lines.push('');
      lines.push(
        '_Recommendation: cover newly-dynamic routes with integration tests for cookie/session paths._',
      );
    }
    lines.push('');
  }

  if (sections.migration) {
    const asyncMig = diagnostics.filter((d) => d.ruleId === 'async-request-api').length;
    if (asyncMig > 0) {
      lines.push('## Migration');
      lines.push('');
      lines.push(
        `Found ${asyncMig} sync usage${asyncMig === 1 ? '' : 's'} of cookies/headers/params/searchParams (Next 15 requires async). Run codemod.`,
      );
      lines.push('');
    }
  }

  if (concise) {
    return lines.slice(0, 30).join('\n');
  }
  return lines.join('\n').trim() + '\n';
}

const HEADING_RE = /^(#{1,6})\s+(.+)$/;
const BOLD_RE = /\*\*(.+?)\*\*/g;
const ITALIC_RE = /(?<!\*)_(.+?)_(?!\*)/g;
const INLINE_CODE_RE = /`([^`]+)`/g;

export function renderMiniMarkdown(src: string): string {
  const lines = src.split('\n');
  const out: string[] = [];
  let inList = false;
  let inCode = false;
  for (const raw of lines) {
    if (raw.startsWith('```')) {
      if (inCode) {
        out.push('</code></pre>');
        inCode = false;
      } else {
        out.push('<pre class="mt-1 mb-2 rounded-sm border border-line bg-bg-subtle p-2 text-[11px] font-mono"><code>');
        inCode = true;
      }
      continue;
    }
    if (inCode) {
      out.push(escapeHtml(raw));
      continue;
    }
    const h = raw.match(HEADING_RE);
    if (h && h[1] && h[2] != null) {
      if (inList) {
        out.push('</ul>');
        inList = false;
      }
      const level = h[1].length;
      const text = inlineFormat(h[2]);
      const cls =
        level === 1
          ? 'text-md font-semibold text-ink-1 mt-3 mb-1'
          : level === 2
            ? 'text-sm font-semibold text-ink-1 mt-3 mb-1 uppercase tracking-caps text-[11px]'
            : 'text-xs font-semibold text-ink-2 mt-2 mb-1';
      out.push(`<h${Math.min(level, 6)} class="${cls}">${text}</h${Math.min(level, 6)}>`);
      continue;
    }
    if (raw.startsWith('- ')) {
      if (!inList) {
        out.push('<ul class="ml-4 list-disc space-y-0.5 text-xs text-ink-2">');
        inList = true;
      }
      out.push(`<li>${inlineFormat(raw.slice(2))}</li>`);
      continue;
    }
    if (inList) {
      out.push('</ul>');
      inList = false;
    }
    if (raw.trim() === '') {
      out.push('<div class="h-1"></div>');
    } else {
      out.push(`<p class="text-xs text-ink-2">${inlineFormat(raw)}</p>`);
    }
  }
  if (inList) out.push('</ul>');
  if (inCode) out.push('</code></pre>');
  return out.join('\n');
}

function inlineFormat(s: string): string {
  return escapeHtml(s)
    .replace(BOLD_RE, '<strong class="text-ink-1">$1</strong>')
    .replace(ITALIC_RE, '<em class="text-ink-3">$1</em>')
    .replace(INLINE_CODE_RE, '<code class="rounded-sm border border-line bg-bg-subtle px-1 font-mono text-[11px] text-ink-1">$1</code>');
}

function escapeHtml(s: string): string {
  return s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');
}
